import Foundation

let original = Workout(title: "벤치 루틴", exercises: [Exercise(sets: [SetEntry(kg: 80, reps: 8, done: true)])])
let copy = original.repeated()
precondition(copy.id != original.id)
precondition(copy.exercises[0].id != original.exercises[0].id)
precondition(copy.exercises[0].sets[0].id != original.exercises[0].sets[0].id)
precondition(!copy.exercises[0].sets[0].done && original.exercises[0].sets[0].done)
precondition(copy.exercises[0].sets[0].kg == 80 && copy.exercises[0].sets[0].reps == 8)
let food = Food(name: "검증용", kcal100: 150, protein100: 20, carbs100: 10, fat100: 3)
let meal = Meal(title: "아침", entries: [MealEntry(food: food, grams: 200)])
let state = AppData(diets: [DietSheet(title: "식단", meals: [meal])], workouts: [original])
let data = try JSONEncoder().encode(state)
let restored = try JSONDecoder().decode(AppData.self, from: data)
precondition(restored.diets[0].kcal == 300)
precondition(restored.workouts[0].exercises[0].sets[0].done)
precondition(restored.diets[0].id == state.diets[0].id)
precondition(Validation.number("-1") == nil && Validation.number("nan") == nil)
precondition(Validation.number("80,5") == 80.5)
precondition(Food.reference.count == 10 && Set(Food.reference.map(\.id)).count == 10)
print("PASS: record round trip, routine copy isolation, nutrition and numeric validation")
